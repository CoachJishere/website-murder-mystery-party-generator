### 특정 친구 그룹에 맞는 캐릭터를 어떻게 만드나요?

친구들의 실제 성격으로 시작하여 빅토리아 맥락으로 번역하세요. 경쟁적인 친구는 야심찬 산업가가 되고, 사교적인 나비는 잘 연결된 사교계 명사로 변신하며, 조용한 관찰자는 신비한 가정교사가 됩니다. 핵심은 시대에 적합한 배경을 추가하면서 핵심 성격 특성을 유지하는 것입니다.

