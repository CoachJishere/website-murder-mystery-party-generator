### 빅토리아 살인 미스터리 단서는 얼마나 복잡해야 하나요?

역사적 진정성과 접근성의 균형을 맞추세요. 전보와 독약 병 같은 시대에 적합한 증거를 사용하되, 명확한 언어로 단서를 작성하세요. 미스터리에 영향을 미치는 빅토리아 관습을 설명하는 맥락 카드를 제공하세요.

### 빅토리아 살인 미스터리 파티의 이상적인 그룹 크기는 얼마인가요?

6~8명의 게스트가 가장 적합합니다. 이 크기는 수사 물류를 압도하지 않으면서 복잡한 캐릭터 관계를 허용합니다. 각 게스트는 2-3명의 다른 캐릭터와 의미 있는 연결을 가질 수 있습니다.

### 정교한 의상에 편안하지 않은 게스트는 어떻게 처리하나요?

완전한 시대 드레스보다 주요 액세서리에 집중하세요. 남성은 회중시계와 나비넥타이가 있는 어두운 정장을 입을 수 있고, 여성은 장갑과 헤어 액세서리가 있는 긴 드레스를 사용할 수 있습니다. 태도가 완벽한 의상보다 더 중요하다는 것을 강조하세요.

