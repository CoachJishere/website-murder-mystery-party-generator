1880-1890년대는 인식 가능한 빅토리아 요소와 극적인 잠재력의 최고 균형을 제공합니다. 이 시기는 산업 부, 신흥 여성 권리 갈등, 그리고 흥미로운 증거 가능성을 만드는 기술 혁신을 포함합니다.

