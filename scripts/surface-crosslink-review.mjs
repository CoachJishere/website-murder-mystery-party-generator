/**
 * Build a human-readable markdown review doc from the latest audit JSON outputs.
 *
 * Reads:
 *   temp-files/crosslink-dead-targets-<ISO>.json — surfaces the ambiguous (0 or
 *     2+ candidate) entries grouped by source slug + per-cell location.
 *   temp-files/crosslink-dead-anchors-<ISO>.json — surfaces each dead anchor
 *     with the closest matching H2 slug from the same cell.
 *
 * Output: temp-files/crosslink-review-<ISO>.md
 *   For each cell, a checklist-style block the reviewer can scan and tick.
 *
 * No DB or map writes. Pure repackaging of the audit output for the human.
 */

import { createClient } from './_supabase-node.mjs';
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import GithubSlugger from 'github-slugger';
import 'dotenv/config';

const SUPABASE_URL = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
const SUPABASE_KEY = process.env.SUPABASE_SERVICE_KEY || process.env.VITE_SUPABASE_ANON_KEY;

function latest(pattern) {
  const files = readdirSync('temp-files').filter(f => f.startsWith(pattern) && f.endsWith('.json')).sort();
  if (!files.length) throw new Error(`No temp-files/${pattern}-*.json found.`);
  return `temp-files/${files[files.length - 1]}`;
}

function extractHeadings(content) {
  const slugger = new GithubSlugger();
  const headings = [];
  for (const m of content.matchAll(/^(#{2,3})\s+(.+)$/gm)) {
    headings.push({ text: m[2].trim(), slug: slugger.slug(m[2].trim()) });
  }
  return headings;
}

// crude similarity: count of shared substrings of length 6
function similarity(a, b) {
  if (!a || !b) return 0;
  let shared = 0;
  for (let i = 0; i <= a.length - 6; i++) {
    if (b.includes(a.slice(i, i + 6))) shared++;
  }
  return shared;
}

function closestHeadings(anchor, headings, n = 3) {
  return headings
    .map(h => ({ ...h, score: similarity(anchor, h.slug) }))
    .sort((a, b) => b.score - a.score)
    .slice(0, n)
    .filter(h => h.score > 0);
}

async function main() {
  const targetsPath = latest('crosslink-dead-targets');
  const anchorsPath = latest('crosslink-dead-anchors');
  console.log(`Targets: ${targetsPath}`);
  console.log(`Anchors: ${anchorsPath}`);
  const targets = JSON.parse(readFileSync(targetsPath, 'utf8'));
  const anchors = JSON.parse(readFileSync(anchorsPath, 'utf8'));

  const supabase = createClient(SUPABASE_URL, SUPABASE_KEY);

  // Pull every affected cell's content once so we can compute heading slugs.
  const affectedSlugs = new Set([...anchors.map(c => `${c.slug}|${c.lang}`), ...(targets.perCell || []).map(c => `${c.slug}|${c.lang}`)]);
  const contentMap = new Map();
  for (const key of affectedSlugs) {
    const [slug, language] = key.split('|');
    const { data } = await supabase
      .from('blog_posts')
      .select('content')
      .eq('slug', slug)
      .eq('language', language)
      .single();
    if (data) contentMap.set(key, data.content);
  }

  let md = `# Cross-link review — ${new Date().toISOString().slice(0, 10)}\n\n`;
  md += `Generated by \`scripts/surface-crosslink-review.mjs\` from \`${targetsPath}\` + \`${anchorsPath}\`.\n\n`;
  md += `Two sections: **ambiguous dead targets** (cross-blog links pointing to slugs that don't exist + have multiple or no candidate substitutes), and **dead anchors** (in-page \`#anchor\` references that don't resolve to any H2 on the page).\n\n`;
  md += `For each item: pick one of [APPLY substitute / RETIRE link / SKIP]. Tell Claude the choices and a follow-up script will execute.\n\n`;
  md += `---\n\n## Ambiguous dead cross-blog targets\n\n`;

  const ambig = (targets.summary || []).filter(t => t.candidates.length !== 1);
  if (!ambig.length) {
    md += `_None._\n\n`;
  } else {
    md += `${ambig.length} distinct dead targets. ${(targets.perCell || []).length} cells reference at least one.\n\n`;
    for (const t of ambig) {
      md += `### \`${t.target}\` (${t.refs} ref${t.refs === 1 ? '' : 's'})\n\n`;
      if (t.candidates.length === 0) {
        md += `- **Candidates:** none (no slug with the same first 30 chars exists in DB)\n`;
        md += `- **Likely action:** RETIRE — remove the link from each cell below, replace with prose. Or pick an unrelated existing slug that fits the link text.\n`;
      } else {
        md += `- **Candidates (${t.candidates.length}):**\n`;
        for (const c of t.candidates) md += `  - \`${c}\`\n`;
        md += `- **Likely action:** APPLY one candidate (your call).\n`;
      }
      // Find every cell-and-language that references this target
      const refs = (targets.perCell || []).filter(c => c.samples.some(s => s.targetSlug === t.target));
      if (refs.length) {
        md += `- **Affected cells:**\n`;
        for (const r of refs) {
          md += `  - [${r.lang}] \`${r.slug}\`\n`;
        }
      }
      md += `\n`;
    }
  }

  md += `---\n\n## Dead anchors\n\n`;
  if (!anchors.length) {
    md += `_None._\n\n`;
  } else {
    md += `${anchors.reduce((a, c) => a + c.n, 0)} dead anchor refs across ${anchors.length} cells.\n\n`;
    md += `For each anchor, the table shows the broken link text, its current dead \`#anchor\`, and the closest matching H2 slugs on the same page. **APPLY** means rewrite the anchor to one of the candidate slugs; **RETIRE** means remove the link wrapper (keep the plain text).\n\n`;
    // Group by source slug for easier scanning
    const bySlug = new Map();
    for (const c of anchors) {
      if (!bySlug.has(c.slug)) bySlug.set(c.slug, []);
      bySlug.get(c.slug).push(c);
    }
    for (const [slug, cells] of [...bySlug].sort((a, b) => b[1].length - a[1].length)) {
      md += `### \`${slug}\` (${cells.length} lang${cells.length === 1 ? '' : 's'})\n\n`;
      for (const cell of cells) {
        const content = contentMap.get(`${cell.slug}|${cell.lang}`);
        const headings = content ? extractHeadings(content) : [];
        md += `**[${cell.lang}]** — ${cell.n} dead anchor${cell.n === 1 ? '' : 's'}\n\n`;
        md += `| Link text | Dead anchor | Closest H2 candidates |\n`;
        md += `|-----------|-------------|----------------------|\n`;
        for (const s of cell.samples) {
          const close = closestHeadings(s.anchor, headings);
          const candCol = close.length ? close.map(h => `\`#${h.slug}\``).join(' / ') : '_no close match_';
          md += `| ${s.text.replace(/\|/g, '\\|')} | \`#${s.anchor}\` | ${candCol} |\n`;
        }
        md += `\n`;
      }
    }
  }

  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  const outPath = `temp-files/crosslink-review-${stamp}.md`;
  writeFileSync(outPath, md);
  console.log(`Review written: ${outPath}`);
  console.log(`Length: ${md.length} chars`);
}

main().catch(err => { console.error(err); process.exit(1); });
