async function translatePosts() {
  console.log('Starting Korean translation batch 8 (posts 36-40)...\n');

  for (let i = 0; i < translations.length; i++) {
    const trans = translations[i];
    console.log(`Processing post ${36 + i}/40: ${trans.koSlug}`);

    // Check if Korean translation already exists
    const { data: existing } = await supabase
      .from('blog_posts')
      .select('id')
      .eq('slug', trans.koSlug)
      .eq('language', 'ko')
      .maybeSingle();

    if (existing) {
      console.log(`⚠️  Korean translation already exists for ${trans.koSlug}, skipping...`);
      continue;
    }

    // Get English post data
    const { data: enPost, error: fetchError } = await supabase
      .from('blog_posts')
      .select('*')
      .eq('slug', trans.enSlug)
      .eq('language', 'en')
      .single();

    if (fetchError || !enPost) {
      console.log(`❌ Error fetching English post: ${trans.enSlug}`);
      continue;
    }

    // Insert Korean translation
    const { error: insertError } = await supabase
      .from('blog_posts')
      .insert({
        title: trans.title,
        content: trans.content,
        slug: trans.koSlug,
        meta_description: trans.metaDescription,
        meta_keywords: enPost.meta_keywords,
        language: 'ko',
        theme: enPost.theme,
        status: 'draft',
        reading_time: enPost.reading_time,
        author: enPost.author,
        tags: enPost.tags,
        published_at: new Date().toISOString(),
        post_date: enPost.post_date
      });

    if (insertError) {
      console.log(`❌ Error inserting Korean post: ${insertError.message}`);
    } else {
      console.log(`✅ ${36 + i}/40 - Korean translation inserted successfully!\n`);
    }
  }

  console.log('\n🎉 Batch 8 translation complete!');
}

