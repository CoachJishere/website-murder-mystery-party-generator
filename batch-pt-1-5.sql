- Permitir que alguns convidados dominem a investigação enquanto outros se tornam observadores passivos
- Criar tarefas de investigação que exigem conhecimento específico em vez de pensamento lógico

- **Fluxo Ótimo de Investigação:** Projete pistas que recompensam diferentes abordagens de investigação, garanta descobertas regulares que avançam a trama e crie oportunidades naturais de colaboração.

