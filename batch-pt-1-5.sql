### Fase 1: A Abertura Convincente (15-20 minutos)

- **O Que Deve Acontecer:** Os convidados precisam entender a situação básica, conhecer seus personagens e se tornar investidos em resolver o mistério. Esta fase deve criar emoção e curiosidade sem sobrecarregar ninguém com muita informação.

- **Objetivos de Ritmo:**
- Estabelecer a premissa do mistério clara e convincentemente
- Permitir tempo para apresentações de personagens e socialização inicial
- Fornecer informação inicial suficiente para iniciar investigação sem resolver tudo
- Criar urgência e motivação para resolver o caso

- **Erros Comuns de Ritmo na Abertura:**
- Apressar apresentações de personagens sem deixar os convidados ficarem confortáveis
- Fornecer muita informação de fundo que sobrecarrega em vez de intrigar
- Começar a investigação imediatamente sem construir atmosfera e investimento
- Tornar a abertura tão complexa que os convidados se sentem confusos em vez de empolgados

- **Estratégia de Abertura Perfeita:** Comece com configuração de cena atmosférica, permita interações naturais de personagens, depois revele o mistério de uma forma que imediatamente faça todos quererem investigar.

