- Criar pistas falsas que parecem injustas ou impossíveis de distinguir de pistas reais

- **Abordagem Estratégica de Desenvolvimento:** Camadas de nova informação que recontextualizam descobertas anteriores, introduza complicações que parecem surpreendentes mas inevitáveis em retrospecto.

### Fase 4: Investigação Climática (15-25 minutos)

- **O Que Deve Acontecer:** Os convidados reúnem pistas finais, testam suas teorias e se preparam para a solução. Esta fase deve parecer urgente e empolgante à medida que tudo se junta.

