async function insertPosts() {
  const results = [];

  for (let i = 0; i < danishPosts.length; i++) {
    try {
      const postNum = 29 + i;
      console.log(`\nInserting Danish post ${postNum}...`);

      const response = await fetch(`${SUPABASE_URL}/rest/v1/blog_posts`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'apikey': SUPABASE_SERVICE_KEY,
          'Authorization': `Bearer ${SUPABASE_SERVICE_KEY}`,
          'Prefer': 'return=representation'
        },
        body: JSON.stringify(danishPosts[i])
      });

      if (!response.ok) {
        const error = await response.text();
        throw new Error(`HTTP error! status: ${response.status}, message: ${error}`);
      }

      const data = await response.json();
      console.log(`✅ Successfully inserted post ${postNum}:`, data[0]?.id);
      console.log('Title:', data[0]?.title);
      console.log('Slug:', data[0]?.slug);

      results.push({ success: true, postNum, id: data[0]?.id });

      // Small delay between requests
      await new Promise(resolve => setTimeout(resolve, 500));

    } catch (error) {
      console.error(`❌ Error inserting post ${29 + i}:`, error);
      results.push({ success: false, postNum: 29 + i, error: error.message });
    }
  }

  console.log('\n=== Summary ===');
  console.log(`Successful: ${results.filter(r => r.success).length}`);
  console.log(`Failed: ${results.filter(r => !r.success).length}`);
}

insertPosts();
