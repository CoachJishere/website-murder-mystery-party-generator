중요한 생명 유지 또는 항법 시스템이 고장 나고, 승무원은 누군가가 그들의 안전을 의도적으로 손상시키고 있다는 것을 깨닫습니다. 그러나 의심되는 사보타주범이 사망한 채 발견되면, 그것은 정의였는가 아니면 더 큰 음모에 대한 목격자 제거였는가?

### 보물 사냥 배신

심해 인양 탐험에서, 누군가가 보물이 이미 비밀리에 제거되었거나 탐험이 밀수나 군사 작전 같은 불법 활동의 은폐라는 것을 발견합니다. 내부고발자는 수중 무덤을 맞이합니다.

### 연구 기지 음모

무단 실험—무기 테스트, 환경 조작, 또는 해양 과학으로 위장한 기업 스파이—이 수행되었습니다. 내부고발자가 폭로를 위협하면, 시설이 수면에 오르기 전에 그들은 제거됩니다.

