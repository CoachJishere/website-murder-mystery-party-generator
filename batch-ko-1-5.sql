**캐릭터 가능성:** 시설이 불법 운영을 숨긴 나이트클럽 주인 (피해자), 범죄 회의를 위한 알리바이를 제공하는 재즈 가수, 보호 서비스가 치명적인 대가를 치른 부패한 경찰 서장, 영역을 확장하는 경쟁 갱 리더, 비밀 작전이 손상된 연방 수사관.

**수사 기회:** 누가 있었는지 보여주는 엔터테인먼트 일정, 자금 세탁을 드러내는 재무 기록, 경찰 보호 협정, 연방 수사 파일, 범죄 활동을 관찰하는 공연자의 목격자 진술.

