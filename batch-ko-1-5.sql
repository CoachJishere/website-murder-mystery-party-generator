겉보기에 단순해 보이는 보험 조사가 청구 조정자가 의심스러운 화재를 조사하다 사망하면서 치명적이 됩니다. 사건은 절망적인 사업주, 부패한 공무원, 전문 범죄자가 관련된 정교한 사기를 드러냅니다.

**캐릭터 네트워크:** 수사가 사기를 위협한 보험 수사관 (피해자), 생존을 위해 사기가 필요한 절망적인 사업주, 사기 청구를 가능하게 하는 부패한 소방서장, "우발적인" 화재를 만드는 전문 방화범, 발견이 위험을 만든 정직한 회계사.

**수사 요소:** 사기 패턴을 보여주는 보험 청구 문서, 절망을 드러내는 사업 재무 기록, 부패를 보여주는 소방서 보고서, 수익 분배를 보여주는 은행 기록.

