import fs from 'fs';

const audit = JSON.parse(fs.readFileSync('./translation-audit-full.json', 'utf8'));

// The audit already calculated this - zh-cn has 49 posts, master has 61, gap is 12
// But we need to figure out WHICH 12 are missing

// Strategy: The zh-cn posts in the audit are the ones that exist
// We need to find the 12 master posts that DON'T have a zh-cn equivalent

// Get all English post IDs from master
const masterPosts = audit.master.posts;

// Get all zh-cn post IDs from the audit
const zhcnPosts = audit.languages['zh-cn'].posts;

console.log(`Master posts: ${masterPosts.length}`);
console.log(`ZH-CN posts: ${zhcnPosts.length}`);
console.log(`Expected gap: ${masterPosts.length - zhcnPosts.length}`);

// The audit file was generated by checking which master posts have translations
// Let's check if the audit has a direct mapping or if we need to infer

// Since the audit shows 49 zh-cn posts exist but doesn't map them to master IDs,
// and the zh-cn posts have their own IDs (not matching master IDs),
// we need to query Supabase for each master post to see if a translation exists

// For now, let's just take ALL 61 master posts as "potentially missing"
// and save them for fetching

const postsToCheck = masterPosts;

fs.writeFileSync('zh-cn-posts-to-verify.json', JSON.stringify(postsToCheck, null, 2));
console.log(`\\nSaved ${postsToCheck.length} posts to zh-cn-posts-to-verify.json`);
console.log('\\nWe will need to check each one against Supabase to see which 12 are actually missing.');
